ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results/evidence_20261020"
DATA = ROOT / "data/evidence_20261020"
TEX = ROOT / "paper/latex"


def read(name):
    return [json.loads(x) for x in (DATA / name).read_text().splitlines()]


def esc(s):
    return str(s).replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")


# These are case-review decisions, not an inferred blacklist of account names.
