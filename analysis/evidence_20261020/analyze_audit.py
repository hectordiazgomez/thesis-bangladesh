"""Reproduce descriptive case-audit outputs from cached public evidence.

Case labels were assigned after individual inspection of the 275 dossiers.
They concern observed activity, not the identity or occupation of a person.
This is an AI-assisted case review, without independent human validation.
No national estimation sample, event definition or archived result is changed.
"""
