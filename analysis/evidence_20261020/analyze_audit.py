def main():
    commits = {(x["repo"], x["sha"]): (x.get("data") or {}).get("object") or {}
               for x in read("public_commits.jsonl")}
    snaps = {x["repo"]: x for x in read("public_snapshots.jsonl")}
    diffs = {(x["repo"], x["sha"]): x for x in read("public_core_commit_diffs.jsonl")}
    profiles = {x["requested_login"]: x for x in read("public_profiles.jsonl")}
    cohort = pd.read_parquet(OUT / "audit_cohorts.parquet").sort_values("login")
    pushes = pd.read_parquet(OUT / "core_pushes.parquet")
    onset = pd.read_parquet(OUT / "onset_commits.parquet")
    events = pd.read_parquet(OUT / "core_repository_events.parquet")
    events = events[events.primary].copy()
    targets = pd.read_csv(OUT / "commit_audit_targets.csv")

    # Freeze an auditable classification of every observed core push head.
    push_rows = []
    for row in pushes.to_dict("records"):
        c = commits.get((row["repo"], row["head_sha"]), {})
        login = row["pusher_login"]
        identity = json.dumps([c.get("author"), c.get("committer")]).lower()
        direct = login in AUTO
        if direct:
            assert any(s in identity for s in ["[bot]", "readme-bot", "pyup-bot", "snyk-bot", "github-actions"]), (login, c)
            assert (row["repo"], row["head_sha"]) in diffs
        status = ("direct" if direct else "suggestive" if login == "hrshadhin"
                  else "unavailable" if not c else "no_direct_evidence")
        push_rows.append({**row, "audit_status": status,
                          "activity_kind": AUTO[login][0] if direct else status,
                          "evidence_url": c.get("url", ""),
                          "head_message": c.get("message", ""),
                          "evidence_reason": AUTO[login][1] if direct else CORE_NOTES[login]})
    pa = pd.DataFrame(push_rows)
    pa.to_parquet(OUT / "core_push_audit.parquet", index=False)
    pa.drop(columns=["push_time"]).to_csv(OUT / "core_push_audit.csv", index=False)
    assert len(pa) == 180

    # Only remove the audited automated HEAD events. Retain all 57 non-push
    # primary events, including branch/PR events plausibly linked to bot updates.
    auto_day = (pa[pa.audit_status.eq("direct")]
                .assign(date=lambda x: x.push_time.dt.tz_localize(None).dt.normalize())
                .groupby(["pusher_login", "date", "repo"]).size().rename("auto_heads").reset_index()
                .rename(columns={"pusher_login": "login", "repo": "repo_name"}))
    ev = events.merge(auto_day, on=["login", "date", "repo_name"], how="left")
    ev["auto_heads"] = ev.auto_heads.fillna(0).where(ev.event_type.eq("PushEvent"), 0).astype(int)
    assert (ev.auto_heads <= ev.event_count).all()
    ev["remaining_events"] = ev.event_count - ev.auto_heads
    ev.to_parquet(OUT / "core_event_decomposition.parquet", index=False)
    summary_rows = []
    for label, col in [("Original primary events", "event_count"),
                       ("Retaining all events except automated heads", "remaining_events")]:
        z = ev[ev[col] > 0]
        days = z[["login", "date"]].drop_duplicates().shape[0]
        summary_rows.append(dict(definition=label, events=int(z[col].sum()), users=z.login.nunique(),
                                 active_user_days=days, daily_rate_pct=100*days/(4*10241)))
    summary = pd.DataFrame(summary_rows)
    summary.to_csv(OUT / "core_sensitivity.csv", index=False)

    # Explicit learning/exercise markers: describe repository content, not
    # occupation. Conservative lexical markers reviewed in the case dossiers.
    learning_pattern = re.compile(
        r"assign?ment|assingment|ass?ingment|practice|learning|learn-|bootcamp|"
        r"problem.solving|problems|100-days-of-code|exercism|dsa|ds_algo|"
        r"data.structure.and.algorithm|cpp-contest|uri-judge|neetcode|"
        r"guided-projects|fullstackcourse|apna-collage|programming.hero|"
        r"ph-university|cse102|cse112|livecodinginterview|kmp-compose-examples|"
        r"b10a2|the-hard-parts-of-object", re.I)
    learning_repos = {r for r in onset.repo.unique() if learning_pattern.search(r.split("/", 1)[1])}
    pd.DataFrame([{"repo": r, "criterion": "Explicit exercise/learning marker in repository name",
                   "evidence_url": next((commits.get((r, s), {}).get("url", "") for s in onset.loc[onset.repo.eq(r), "sha"] if commits.get((r,s),{})), "")}
                  for r in sorted(learning_repos)]).to_csv(OUT / "learning_marker_repositories.csv", index=False)

    case_rows, dossiers = [], []
    for i, row in enumerate(cohort.to_dict("records"), 1):
        login = row["login"]
        tt = targets[targets.login.eq(login)].drop_duplicates(["repo", "sha"])
        cs = [{"repo": r.repo, "sha": r.sha, "source": r.source,
               **commits.get((r.repo, r.sha), {})} for r in tt.itertuples()]
        rr = []
        for repo in sorted(tt.repo.unique()):
            s = snaps.get(repo, {})
            node = s.get("data") or {}
            workflows = []
            for w in (node.get("workflows") or {}).get("entries", []):
                if (w.get("object") or {}).get("text") is not None:
                    workflows.append({"path": ".github/workflows/"+w["name"], "text": w["object"]["text"], "sha": s["sha"]})
            rr.append({"repo": repo, "sha": s.get("sha"), "status": s.get("status"),
                       "workflows": workflows,
                       "readme": (node.get("readme") or node.get("readme_lower") or {}).get("text")})
        if login in AUTO:
            status, reason = "direct", AUTO[login][1]
        elif login == "mhnarfth":
            status, reason = "mixed", CORE_NOTES[login]
        elif login in ["hrshadhin", "shadowshahriar"]:
            status = "suggestive"
            reason = CORE_NOTES.get(login, "Ten daily README duration updates; unchanged solved-problem counts; no recovered unattended publisher. No new source-code changes in these commits.")
        elif row["core_public_active"]:
            status = "unavailable_or_insufficient" if login in ["antonin686", "pratyai", "zihadulislam99", "manojgain1988"] else "no_direct_evidence"
            reason = CORE_NOTES[login]
        else:
            status = "no_direct_evidence" if any(c.get("oid") for c in cs) else "unavailable_or_insufficient"
            examples = list(dict.fromkeys(c.get("message", "").split("\n")[0] for c in cs if c.get("message")))[:3]
            reason = "Inspected commit messages, author/committer identities and available historical workflows; no identified automatic publisher. Examples: " + " | ".join(examples)
        core_push = pa[pa.pusher_login.eq(login)]
        learning = bool(set(tt.repo) & learning_repos)
        evl = events[events.login.eq(login)]
        case_rows.append({"case_id": f"C{i:03}", "login": login, "core": row["core_public_active"],
                          "onset": row["onset_author"], "status": status, "reason": reason,
                          "core_events": int(evl.event_count.sum()), "core_pushes": len(core_push),
                          "automated_core_heads": int(core_push.audit_status.eq("direct").sum()),
                          "onset_commits": int(onset.pusher_login.eq(login).sum()),
                          "available_audited_commits": sum(bool(c.get("oid")) for c in cs),
                          "audited_targets": len(cs), "learning_marker": learning,
                          "repositories": " | ".join(sorted(tt.repo.unique())),
                          "evidence_urls": " | ".join(c.get("url", "") for c in cs if c.get("url"))})
        dossiers.append(dict(login=login, case_id=f"C{i:03}", core=bool(row["core_public_active"]),
                             onset=bool(row["onset_author"]), status=status, reason=reason,
                             profile=profiles.get(login), commits=cs, repos=rr))
    cases = pd.DataFrame(case_rows)
    cases.to_csv(OUT / "individual_case_review.csv", index=False)
    (OUT / "review_dossiers.jsonl").write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in dossiers)+"\n")

    # Keep the established onset definition next to narrower telemetry endpoints.
    timing = []
    for endpoint in ["2024-07-23T12:00:00Z", "2024-07-23T13:00:00Z", "2024-07-24T00:00:00Z"]:
        z = onset[onset.authored_time.lt(endpoint)]
        timing.append({"author_end_exclusive_utc": endpoint, "commits": len(z), "users": z.pusher_login.nunique(),
                       "pushed_before_endpoint": int(z.push_time.lt(endpoint).sum()),
                       "pushed_from_jul24": int(z.push_time.ge("2024-07-24").sum())})
    pd.DataFrame(timing).to_csv(OUT / "author_endpoint_sensitivity.csv", index=False)

    # Correct the ancillary weekend feature in NEW outputs, preserving Oct 19.
    p = pd.read_parquet(ROOT / "data/processed/github_activity_international_enriched.parquet")
    p.date = pd.to_datetime(p.date)
    pre = p[p.country.eq("Bangladesh") & p.date.lt("2024-07-18")].copy()
    pre.login = pre.login.str.lower()
    pre["productive"] = pre.productive_events.gt(0)
    wk = pre.assign(frisa=lambda x: x.productive & x.date.dt.dayofweek.isin([4, 5]),
                    satsun=lambda x: x.productive & x.date.dt.dayofweek.isin([5, 6])).groupby("login").agg(
                        active=("productive", "sum"), frisa=("frisa", "sum"), satsun=("satsun", "sum"))
    wk["frisa_share_pct"] = 100*wk.frisa/wk.active.replace(0, np.nan)
    wk["satsun_share_pct"] = 100*wk.satsun/wk.active.replace(0, np.nan)
    features = pd.read_parquet(ROOT / "results/advisor_20261019/residual_user_characteristics_with_age.parquet")
    features.login = features.login.str.lower()
    features = features.merge(wk.reset_index(), on="login", validate="one_to_one")
    features.to_parquet(OUT / "residual_features_corrected_weekend.parquet", index=False)
    feature_rows = []
    for name, mask in [
        ("All eligible", pd.Series(True, index=features.index)),
        ("Core publishers", features.core_public_active),
        ("Core with automated heads", features.login.isin(AUTO)),
        ("Other core publishers", features.core_public_active & ~features.login.isin(AUTO)),
        ("Other eligible users", ~features.core_public_active),
        ("Onset authors", features.onset_author)]:
        z = features[mask]
        feature_rows.append(dict(group=name, users=len(z), activity_pct=z.pre_activity_pct.mean(),
                                 median_pushes=z.pre_pushes.median(), weekend_frisa=z.frisa_share_pct.mean(),
                                 old_weekend_satsun=z.satsun_share_pct.mean()))
    fs = pd.DataFrame(feature_rows)
    fs.to_csv(OUT / "feature_comparison.csv", index=False)

    direct_onset = []
    for r in onset.itertuples():
        c = commits.get((r.repo, r.sha), {})
        ident = json.dumps([c.get("author"), c.get("committer")]).lower()
        if any(k in ident for k in ["[bot]", "readme-bot", "pyup-bot", "snyk-bot", "github-actions"]):
            direct_onset.append((r.repo, r.sha))
    assert direct_onset == [("mhnarfth/netgroup", "1f402fb03a2968d937684f120ebd546e6c8ffe44")]
    statistics = dict(
        automated_core_heads=int(pa.audit_status.eq("direct").sum()), automated_core_accounts=len(AUTO),
        core_head_categories=pa.groupby("audit_status").size().to_dict(),
        auto_kind_counts=pa[pa.audit_status.eq("direct")].groupby("activity_kind").size().to_dict(),
        core_case_status=cases[cases.core].groupby("status").size().to_dict(),
        retrieved_commits=sum(bool(x) for x in commits.values()), requested_commits=len(commits),
        core_sensitivity=summary.to_dict("records"),
        onset_direct_automated_commits=len(direct_onset), onset_duration_only_commits=10,
        onset_unchanged_count=len(onset), onset_without_direct_automation=len(onset)-1,
        onset_without_direct_and_duration_only=len(onset)-11,
        explicit_learning_accounts=int(cases[cases.onset].learning_marker.sum()),
        explicit_learning_repositories=len(learning_repos),
        explicit_learning_commits=int(onset.repo.isin(learning_repos).sum()),
        timing=timing, features=feature_rows,
    )
    (OUT / "audit_summary.json").write_text(json.dumps(statistics, indent=2))

    # Tables: activity decomposition and the covariates after separating the
    # directly evidenced automatic publication group.
    rows = []
    for r in summary.to_dict("records"):
        label = "All primary events" if r["definition"].startswith("Original") else "Excluding automated push heads only"
        rows.append(f"{label} & {r['events']} & {r['users']} & {r['active_user_days']} & {r['daily_rate_pct']:.3f}" + r" \\")
    table = r"""\begin{table}[htbp]
\centering\small
\caption{Residual publication on July 19--22: original counts and case-audit sensitivity}
\label{tab:evidence_audit}
\begin{threeparttable}
\begin{tabular}{@{}p{0.44\textwidth}rrrr@{}}
\toprule
Definition & Events & Users & User-days & Rate (\%) \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\begin{tablenotes}[flushleft]\footnotesize
\item The daily rate divides active user-days by $4\times10{,}241$. Exclusion applies only to PushEvents with directly evidenced automated head commits; all other primary events remain, including possibly related branch and pull-request events. A head audit does not classify every commit in its push. These are descriptive sensitivities, not revised national estimates or validated counts of human work. The original sample and outcome remain unchanged.
\end{tablenotes}\end{threeparttable}
\end{table}
"""
    (TEX / "tables/tab_evidence_audit.tex").write_text(table)
    rows = [f"{esc(r.group)} & {r.users:,} & {r.activity_pct:.2f} & {r.median_pushes:.1f} & {r.weekend_frisa:.2f}" + r" \\"
            for r in fs.itertuples()]
    (TEX / "tables/tab_evidence_features.tex").write_text(r"""\begin{table}[htbp]
\centering\small
\caption{Pre-period activity and the automation component of residual publication}
\label{tab:evidence_features}
\begin{threeparttable}
\begin{tabular}{@{}p{0.38\textwidth}rrrr@{}}
\toprule
Group & Users & Active days (\%) & Pushes & Fri--Sat (\%) \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule\end{tabular}
\begin{tablenotes}[flushleft]\footnotesize
\item May 1--July 17. Active days is the mean percentage of the 78 days; pushes is the median count. Fri--Sat is the mean account-level share of active days falling on Bangladesh's Friday--Saturday weekend (using UTC day labels), conditional on at least one active day. Grouping by automated heads concerns observed July 19--22 activity, not account type. Onset authors overlap with other groups. No causal or occupational interpretation is implied.
\end{tablenotes}\end{threeparttable}\end{table}
""")
    # All 40 case summaries, using stable case IDs linked to the repository CSV.
    labels = {"direct": "Direct", "mixed": "Mixed", "suggestive": "Suggestive",
              "unavailable_or_insufficient": "Insufficient", "no_direct_evidence": "Not identified"}
    cr = []
    for r in cases[cases.core].itertuples():
        cr.append(f"{r.case_id} & {r.core_events} & {r.automated_core_heads} & {labels[r.status]} & {esc(r.reason)}" + r" \\")
    (TEX / "tables/tab_evidence_cases.tex").write_text(r"""{\footnotesize\setlength{\tabcolsep}{3pt}
\begin{longtable}{@{}p{.065\textwidth}rrp{.13\textwidth}p{.61\textwidth}@{}}
\caption{Individual review of every core-window publisher}\label{tab:evidence_cases}\\
\toprule Case & Events & Auto & Evidence & Basis and qualification \\
\midrule\endfirsthead
\toprule Case & Events & Auto & Evidence & Basis and qualification \\
\midrule\endhead
\bottomrule\endfoot
""" + "\n".join(cr) + r"""
\end{longtable}}
\noindent\footnotesize Events counts all primary events on July 19--22; Auto counts only directly evidenced automated push heads. ``Not identified'' is not proof of manual authorship. Mixed denotes the account with a generated onset-authored commit alongside other activity; that generated commit is not itself a core push head. Case IDs map to account/repository/commit URLs and dated API evidence in \texttt{results/evidence\_20261020/individual\_case\_review.csv}. The review is AI-assisted and has not been independently validated by a second reviewer.\normalsize
""")
    plt.rcParams.update({"font.family": "serif", "font.size": 10, "pdf.fonttype": 42})
    daily = pa.assign(day=pa.push_time.dt.strftime("%b %d")).groupby(["day", "audit_status"]).size().unstack(fill_value=0)
    fig, ax = plt.subplots(figsize=(7.4, 3.3))
    bottom = np.zeros(len(daily))
    for key, label, color in [
        ("direct", "Direct automation evidence", "#3c5a75"),
        ("suggestive", "Suggestive only", "#9bb4c7"),
        ("no_direct_evidence", "No direct evidence found", "#b4b4b4"),
        ("unavailable", "Historical object unavailable", "#eeeeee")]:
        v = daily.get(key, pd.Series(0, index=daily.index))
        ax.bar(daily.index, v, bottom=bottom, label=label, color=color, edgecolor="white", linewidth=.5)
        bottom += v.to_numpy()
    ax.set_ylabel("Observed PushEvents")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, loc="upper center", bbox_to_anchor=(.5, -.12), ncol=2, fontsize=9)
    fig.subplots_adjust(bottom=.25, left=.1, right=.98, top=.95)
    fig.savefig(TEX / "figures/fig_evidence_automation.pdf")
    plt.close(fig)
    print(json.dumps(statistics, indent=2))


if __name__ == "__main__":
    main()
