"""Regenerate the data-driven LaTeX tables of the manuscript.

Usage (from the repository root):

    python analysis/tables/make_all_tables.py

Every number is read from stored result files (primarily results/final/);
nothing is re-estimated. Output: paper/latex/tables/*.tex (booktabs +
threeparttable fragments that are \\input{} by the manuscript).

Requirements: pandas.
"""

