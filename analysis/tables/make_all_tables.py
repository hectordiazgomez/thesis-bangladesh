def tab_sc_placebos(sc: dict) -> None:
    p = pd.read_csv(RES / "synthetic_control" / "sc_inspace_placebos.csv")
    fin = pd.read_csv(FINAL / "table_primary_SC_placebos.csv").set_index("country")
    for r in p[p.country != "Bangladesh"].itertuples():
        check(f"placebo {r.country}", r.RMSPE_ratio, fin.loc[r.country, "RMSPE_ratio"], 1e-5)
    p = p.sort_values("RMSPE_ratio", ascending=False).reset_index(drop=True)
    rows = []
    for i, r in enumerate(p.itertuples(), 1):
        name = r"\textbf{Bangladesh}" if r.country == "Bangladesh" else r.country
        rows.append(f"{i} & {name} & {num(r.ATT)} & {num(r.pre_RMSPE)} & {num(r.post_RMSPE)} & "
                    f"{num(r.RMSPE_ratio)}")
    n = len(p)
    p_ratio = (p.RMSPE_ratio >= sc["ratio"]).sum() / n
    p_att = (p.ATT.abs() >= abs(sc["att"])).sum() / n
    check("rank p ratio", p_ratio, 1 / 15, 1e-9)
    check("rank p att", p_att, 1 / 15, 1e-9)
    note = (rf"Each donor country is assigned the July 18--23 treatment in turn and its synthetic "
            rf"control is rebuilt from the remaining donors. Units are ordered by the post/pre "
            rf"RMSPE ratio. Bangladesh has both the largest ratio and the largest absolute ATT "
            rf"among the {n} units, so the exact rank $p$-value is $1/{n}={p_ratio:.4f}$ for "
            rf"both statistics. This is the minimum attainable value with 14 placebo countries; "
            rf"inference resolution is limited by the size of the donor pool.")
    write("tab_sc_placebos", table(
        "Synthetic-control in-space placebo inference", "tab:sc_placebos", "rlrrrr",
        r"Rank & Unit & ATT (pp) & Pre RMSPE & Post RMSPE & Ratio", rows, note,
        size=r"\footnotesize"))


