def num(x: float, d: int = 3, suffix: str = "") -> str:
    """Format a number with a typographic minus sign."""
    s = f"{x:,.{d}f}"
    if s.startswith("-"):
        s = "$-$" + s[1:]
    return s + suffix


def pct(x: float, d: int = 1) -> str:
    return num(x, d, r"\%")


def check(label: str, got: float, expected: float, tol: float = 1e-3) -> None:
    if not np.isclose(got, expected, atol=tol):
        raise AssertionError(f"{label}: {got} != {expected}")


def write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    header = (f"% Generated by analysis/tables/make_all_tables.py -- do not edit by hand.\n")
    (OUT / f"{name}.tex").write_text(header + body)
    print(f"wrote {(OUT / (name + '.tex')).relative_to(REPO)}")


