APPENDIX_LABELS = {"tab:weights", "tab:loo", "tab:sc_placebos", "tab:weights_specific",
                   "tab:rdit", "tab:mech_placebos", "tab:metadata", "tab:push_completeness",
                   "tab:push_size", "tab:concentration", "tab:sector_threshold",
                   "tab:sector_fixed_repo"}


def table(caption: str, label: str, colspec: str, head: str, rows: list[str],
          note: str, size: str = r"\small", width: str | None = None) -> str:
    """booktabs/threeparttable float. `width` widens very narrow tables (via
    tabular*) so their notes are not set in a cramped column."""
    placement = "H" if label in APPENDIX_LABELS else "htbp"
    if width:
        begin = f"\\begin{{tabular*}}{{{width}}}{{@{{\\extracolsep{{\\fill}}}}{colspec}}}\n"
        end = "\\end{tabular*}\n"
    else:
        begin, end = f"\\begin{{tabular}}{{{colspec}}}\n", "\\end{tabular}\n"
    return (
        f"\\begin{{table}}[{placement}]\n\\centering\n" + size + "\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        "\\begin{threeparttable}\n"
        + begin + f"\\toprule\n{head} \\\\\n\\midrule\n"
        + " \\\\\n".join(rows) + " \\\\\n\\bottomrule\n" + end
        + f"\\begin{{tablenotes}}[flushleft]\n\\footnotesize\\raggedright\n\\item \\textit{{Notes:}} {note}\n"
        + "\\end{tablenotes}\n\\end{threeparttable}\n\\end{table}\n"
    )


